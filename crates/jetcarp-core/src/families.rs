#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FamilyKind {
    /// One prototile whose corners come from parameters; edges can be reshaped.
    Reshapeable,
    /// Fixed polygons in a unit cell with explicit lattice vectors.
    Static,
    /// Aperiodic, generated by substitution.
    Aperiodic,
}

#[derive(Clone, Debug)]
pub struct Family {
    pub id: &'static str,
    pub name: &'static str,
    pub group: &'static str,
    pub sym: &'static str,
    pub note: &'static str,
    pub kind: FamilyKind,
    pub classes: &'static [EdgeClass],
}

macro_rules! cls {
    ($( [$($e:expr),*] $k:ident ),* $(,)?) => {
        &[ $( EdgeClass { edges: &[$($e),*], kind: GlueKind::$k, orient: &[] } ),* ]
    };
}

