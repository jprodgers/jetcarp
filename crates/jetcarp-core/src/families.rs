pub fn family(id: &str) -> Option<&'static Family> {
    FAMILIES
        .iter()
        .find(|f| f.id == id)
        .or_else(|| crate::isohedral::family(id))
}

/// A family id for a name people (and language models) use for a tiling: the id itself, a
/// vertex configuration (`3.4.6.4`, `4.8.8`, `3^6`, `6.6.6`, `4^4`, spaces or `^` allowed), a word
/// from the family's name (`rhombitrihexagonal`, `snub square`, `trihexagonal`), or a common
/// alias (`hexagons`, `honeycomb`, `triangles`, `penrose`). Case-insensitive.
pub fn alias(name: &str) -> Option<&'static str> {
    let low = name.trim().to_ascii_lowercase();
    if let Some(f) = family(&low) {
        return Some(f.id);
    }
    let squashed: String = low
        .chars()
        .filter(|c| !matches!(c, ' ' | '_' | '-'))
        .collect();
    // Vertex configurations, with exponents written out: 3^2.4.3.4 -> 3.3.4.3.4.
    let expand = |s: &str| -> String {
        s.split('.')
            .flat_map(|part| match part.split_once('^') {
                Some((b, e)) => {
                    let n: usize = e.parse().unwrap_or(1);
                    vec![b.to_string(); n.max(1)]
                }
                None => vec![part.to_string()],
            })
            .collect::<Vec<_>>()
            .join(".")
    };
    let vc = expand(&squashed.replace(['(', ')'], ""));
    let by_vertex = match vc.as_str() {
        "4.4.4.4" => Some("square"),
        "6.6.6" => Some("hex"),
        "3.3.3.3.3.3" => Some("triangle"),
        _ => FAMILIES.iter().find_map(|f| {
            let first = f.name.split(' ').next().unwrap_or("");
            (first.contains('.') && first == vc).then_some(f.id)
        }),
    };
    if by_vertex.is_some() {
        return by_vertex;
    }
    let word = match squashed.as_str() {
        "hexagon" | "hexagons" | "hexagonal" | "honeycomb" => Some("hex"),
        "squares" | "grid" | "moore" | "squaregrid" => Some("square"),
        "triangles" | "triangular" => Some("triangle"),
        "pentagon" | "pentagons" | "cairopentagonal" => Some("cairo"),
        "kites" | "kitesanddarts" | "penrose" | "p2" => Some("penrose-kd"),
        "rhombs" | "p3" => Some("penrose-rhomb"),
        "flathex" | "hexflat" | "flattophex" => Some("hex_flat"),
        _ => None,
    };
    if word.is_some() {
        return word;
    }
    // A word of the Archimedean names: "rhombitrihexagonal", "snub square", "truncated square".
    FAMILIES.iter().find_map(|f| {
        let mut words = f.name.split(' ');
        let first = words.next().unwrap_or("");
        let rest: String = words.collect::<Vec<_>>().join("").to_ascii_lowercase();
        (first.contains('.') && !rest.is_empty() && rest == squashed).then_some(f.id)
    })
}

