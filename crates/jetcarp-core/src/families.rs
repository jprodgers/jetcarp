/// Default edge shapes, as the prototype's `freshEdges` (including its seeded curves).
pub fn fresh_edges(f: &Family) -> Vec<EdgeShape> {
    let n = |t, d| Node { t, d };
    let seed: Option<Vec<EdgeShape>> = match f.id {
        "lizard" => Some(vec![
            EdgeShape {
                mode: EdgeMode::J,
                curved: true,
                nodes: vec![n(0.3, 0.2), n(0.7, -0.22)],
            },
            EdgeShape {
                mode: EdgeMode::J,
                curved: true,
                nodes: vec![n(0.5, 0.26)],
            },
            EdgeShape {
                mode: EdgeMode::J,
                curved: true,
                nodes: vec![n(0.3, -0.2), n(0.72, 0.16)],
            },
        ]),
        "spectre" => Some(vec![EdgeShape {
            mode: EdgeMode::S,
            curved: true,
            nodes: vec![n(0.25, 0.13), n(0.5, 0.0), n(0.75, -0.13)],
        }]),
        _ => None,
    };
    seed.unwrap_or_else(|| {
        f.classes
            .iter()
            .map(|c| EdgeShape::straight_for(c.kind))
            .collect()
    })
}

fn pt(v: &Value, key: &str) -> Result<P, String> {
    let a = v
        .get(key)
        .ok_or_else(|| format!("missing parameter '{key}'"))?;
    point(a).ok_or_else(|| format!("parameter '{key}' is not a point"))
}
fn point(a: &Value) -> Option<P> {
    let arr = a.as_array()?;
    Some([arr.first()?.as_f64()?, arr.get(1)?.as_f64()?])
}
fn num(v: &Value, key: &str) -> Result<f64, String> {
    v.get(key)
        .and_then(|x| x.as_f64())
        .ok_or_else(|| format!("missing number '{key}'"))
}
fn pts(v: &Value, key: &str, n: usize) -> Result<Vec<P>, String> {
    let arr = v
        .get(key)
        .and_then(|x| x.as_array())
        .ok_or_else(|| format!("missing point list '{key}'"))?;
    let out: Option<Vec<P>> = arr.iter().map(point).collect();
    let out = out.ok_or_else(|| format!("'{key}' must be a list of points"))?;
    if out.len() != n {
        return Err(format!("'{key}' needs {n} points, got {}", out.len()));
    }
    Ok(out)
}

/// Corner polygon of a reshapeable family's prototile.
pub fn corners(id: &str, p: &Value) -> Result<Vec<P>, String> {
    if let Some(c) = crate::isohedral::corners(id, p) {
        return c;
    }
    Ok(match id {
        "lizard" => {
            let s = num(p, "s")?;
            let o = pt(p, "o")?;
            let v = pt(p, "v")?;
            let a = [0.0, 0.0];
            let c = [s * 1.5, s * S3 / 2.0];
            let e = [0.0, s * S3];
            let (v1, v3, v5) = (add(o, a), add(o, c), add(o, e));
            let v0 = add(v, [-0.5 * s, s * S3 / 2.0]);
            let v2 = rot_about(v0, v1, -120.0);
            let v4 = rot_about(v2, v3, -120.0);
            vec![v0, v1, v2, v3, v4, v5]
        }
        "hex" | "brick" => {
            let (a, b, c) = (pt(p, "a")?, pt(p, "b")?, pt(p, "c")?);
            vec![[0.0, 0.0], a, add(a, b), add(add(a, b), c), add(b, c), c]
        }
        "square" => {
            let (a, b) = (pt(p, "a")?, pt(p, "b")?);
            vec![[0.0, 0.0], a, add(a, b), b]
        }
        "quad" => pts(p, "v", 4)?,
        "triangle" => pts(p, "v", 3)?,
        "glide" => {
            let (w, h) = (num(p, "w")?, num(p, "h")?);
            vec![[0.0, 0.0], [w, 0.0], [w, h], [0.0, h]]
        }
        "fourfold" => {
            let s = num(p, "s")?;
            vec![[0.0, 0.0], [s, 0.0], [s, s], [0.0, s]]
        }
        "cairo" => {
            let (v0, v1, v2) = (pt(p, "v0")?, pt(p, "v1")?, pt(p, "v2")?);
            let m = [(v0[0] + v1[0]) / 2.0, (v0[1] + v1[1]) / 2.0];
            let v3 = rot_about(v1, v2, -90.0);
            let mut v4 = rot_about(v2, m, 90.0);
            let test = rot_about(v3, v4, -90.0);
            if dist(test, v0) > 1e-6 {
                v4 = rot_about(v2, m, -90.0);
            }
            vec![v0, v1, v2, v3, v4]
        }
        "spectre" => crate::spectre::SPECTRE.to_vec(),
        _ => return Err(format!("family '{id}' has no parametric corners")),
    })
}

/// Unit cell of a static family: lattice vectors and the polygons in one cell.
pub fn static_cell(id: &str, params: &Value) -> Option<(P, P, Vec<Vec<P>>)> {
    if id == "periodic" {
        return crate::catalog::from_params(params).ok();
    }
    if let Some(t) = crate::catalog::get(id) {
        return Some((t.a1, t.a2, t.polys.clone()));
    }
    Some(match id {
        // Two flat-top hexagons (side 1) per 3 x sqrt(3) unit cell, in columns: type 0 at
        // (1, 1/2) and type 1 half a row lower at (5/2, 1/2 + sqrt(3)/2). The basis is kept as
        // given (see `topology::lattice_def`), so unit-cell rows stay horizontal.
        "hex_flat" => {
            let hex = |cx: f64, cy: f64| -> Vec<P> {
                [
                    [1.0, 0.0],
                    [0.5, S3 / 2.0],
                    [-0.5, S3 / 2.0],
                    [-1.0, 0.0],
                    [-0.5, -S3 / 2.0],
                    [0.5, -S3 / 2.0],
                ]
                .iter()
                .map(|d| [cx + d[0], cy + d[1]])
                .collect()
            };
            (
                [3.0, 0.0],
                [0.0, S3],
                vec![hex(1.0, 0.5), hex(2.5, 0.5 + S3 / 2.0)],
            )
        }
        "oct" => {
            let w = 1.0 + std::f64::consts::SQRT_2;
            let (r, h) = (w / 2.0, 0.5);
            (
                [w, 0.0],
                [0.0, w],
                vec![
                    vec![
                        [-h, -r],
                        [h, -r],
                        [r, -h],
                        [r, h],
                        [h, r],
                        [-h, r],
                        [-r, h],
                        [-r, -h],
                    ],
                    vec![[r, h], [w - h, r], [r, w - h], [h, r]],
                ],
            )
        }
        "trihex" => {
            let hex: Vec<P> = (0..6)
                .map(|i| {
                    let (s, c) = crate::detmath::sin_cos(i as f64 * std::f64::consts::PI / 3.0);
                    [c, s]
                })
                .collect();
            (
                [2.0, 0.0],
                [1.0, S3],
                vec![
                    hex,
                    vec![[1.0, 0.0], [1.5, S3 / 2.0], [0.5, S3 / 2.0]],
                    vec![[1.5, S3 / 2.0], [2.5, S3 / 2.0], [2.0, S3]],
                ],
            )
        }
        "herring" => (
            [1.0, 1.0],
            [2.0, -2.0],
            vec![
                vec![[0.0, 0.0], [2.0, 0.0], [2.0, 1.0], [0.0, 1.0]],
                vec![[2.0, -1.0], [3.0, -1.0], [3.0, 1.0], [2.0, 1.0]],
            ],
        ),
        "pyth" => {
            let (a, b) = (1.6, 0.9);
            (
                [a, b],
                [-b, a],
                vec![
                    vec![[0.0, 0.0], [a, 0.0], [a, a], [0.0, a]],
                    vec![[a, 0.0], [a + b, 0.0], [a + b, b], [a, b]],
                ],
            )
        }
        _ => return None,
    })
}

/// Corners the editor can drag, per family (the prototype's `handles`).
pub fn handles(id: &str) -> &'static [usize] {
    if let Some(h) = crate::isohedral::handles(id) {
        return h;
    }
    match id {
        "lizard" => &[0],
        "hex" => &[1, 2, 5],
        "brick" => &[1],
        "square" => &[1, 3],
        "quad" => &[0, 1, 2, 3],
        "triangle" => &[0, 1, 2],
        "glide" => &[2],
        "cairo" => &[2],
        _ => &[],
    }
}

fn set_pt(p: &mut Value, key: &str, v: P) {
    p[key] = json!([v[0], v[1]]);
}

/// Move a corner handle to `pt`, updating the parameters the way the prototype does.
pub fn set_handle(id: &str, p: &mut Value, corner: usize, pt: P) {
    if crate::isohedral::set_handle(id, p, corner, pt) {
        return;
    }
    match (id, corner) {
        ("lizard", 0) => {
            let s = p.get("s").and_then(|x| x.as_f64()).unwrap_or(1.0);
            set_pt(p, "v", [pt[0] + 0.5 * s, pt[1] - s * S3 / 2.0]);
        }
        ("hex", 1) => set_pt(p, "a", pt),
        ("hex", 2) => {
            let a = pt_or(p, "a");
            set_pt(p, "b", sub(pt, a));
        }
        ("hex", 5) => set_pt(p, "c", pt),
        ("brick", 1) => {
            let total = pt_or(p, "a")[0] + pt_or(p, "b")[0];
            let x = pt[0].clamp(0.06, total - 0.06);
            set_pt(p, "a", [x, 0.0]);
            set_pt(p, "b", [total - x, 0.0]);
        }
        ("square", 1) => set_pt(p, "a", pt),
        ("square", 3) => set_pt(p, "b", pt),
        ("quad", i) | ("triangle", i) => {
            if let Some(arr) = p.get_mut("v").and_then(|v| v.as_array_mut())
                && i < arr.len()
            {
                arr[i] = json!([pt[0], pt[1]]);
            }
        }
        ("glide", 2) => {
            p["w"] = json!(pt[0].max(0.3));
            p["h"] = json!(pt[1].max(0.3));
        }
        ("cairo", 2) => set_pt(p, "v2", pt),
        _ => {}
    }
}

fn pt_or(p: &Value, key: &str) -> P {
    p.get(key).and_then(point).unwrap_or([0.0, 0.0])
}

/// Tile JSON in the prototype's format.
pub fn tile_json(f: &Family, params: &Value, edges: Option<&[EdgeShape]>) -> Value {
    json!({
        "family": f.id,
        "symmetry": f.sym,
        "params": params,
        "edges": edges,
    })
}

