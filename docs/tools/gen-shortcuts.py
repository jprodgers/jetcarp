#!/usr/bin/env python3
"""Generate the tables of keys in docs/src/guides/keyboard.md from the app's own table.

Source: `jetcarp shortcuts --json`, the table *Help → Keyboard shortcuts* shows (moving about, the
menus' shortcuts, the grid's cell cursor), with each key as Windows and Linux write it and as
macOS does. The tables between the page's GENERATED markers are replaced; the rest of the page
is hand-written. The page's sentence "The menus have N shortcuts" must give the program's count,
or the generator stops.

Standard library only. Usage: python3 docs/tools/gen-shortcuts.py [--jetcarp target/release/jetcarp] [--check]
"""

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

DOCS = Path(__file__).resolve().parent.parent
REPO = DOCS.parent
PAGE = DOCS / "src" / "guides" / "keyboard.md"
BEGIN = "<!-- GENERATED by docs/tools/gen-shortcuts.py: do not edit by hand -->"
END = "<!-- END GENERATED -->"


def cell(text):
    """A table cell: its keys in code, `|` escaped, and a dash where there is nothing."""
    if not text:
        return "–"
    return text.replace("|", "\\|")


def keys(text):
    if not text:
        return "–"
    # Each key of a list ("Tab, Shift+Tab", "S or →") in code of its own.
    parts = re.split(r"(, | or )", text)
    return "".join(p if p in (", ", " or ") else f"<kbd>{cell(p)}</kbd>" for p in parts)


def tables(groups):
    out = []
    for g in groups:
        out.append(f"### {g['name']}")
        out.append("")
        out.append("| Windows and Linux | macOS | What it does |")
        out.append("| --- | --- | --- |")
        for s in g["keys"]:
            out.append(f"| {keys(s['keys'])} | {keys(s['mac'])} | {cell(s['what'])} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jetcarp", default=str(REPO / "target" / "release" / "jetcarp"))
    ap.add_argument("--check", action="store_true", help="only check that the page is up to date")
    args = ap.parse_args()
    out = subprocess.run([args.jetcarp, "shortcuts", "--json"], capture_output=True, text=True, check=True).stdout
    groups = json.loads(out)["groups"]

    page = PAGE.read_text(encoding="utf-8")
    if BEGIN not in page or END not in page:
        sys.exit(f"{PAGE.name} has no generated section (markers {BEGIN} ... {END})")
    menus = next((g for g in groups if g["name"] == "The menus' shortcuts"), None)
    if menus is None:
        sys.exit("the program's table has no group of the menus' shortcuts")
    n = sum(1 for s in menus["keys"] if s["keys"] and s["mac"])
    said = re.search(r"The menus have (\d+) shortcuts", page)
    if not said or int(said.group(1)) != n:
        sys.exit(f"{PAGE.name} says {said.group(1) if said else 'no number of'} shortcuts for the menus; "
                 f"the program has {n}: correct the sentence")
    head, rest = page.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new = head + BEGIN + "\n\n" + tables(groups) + "\n" + END + tail
    if args.check:
        if new != page:
            print(f"{PAGE.name} is out of date: run python3 docs/tools/gen-shortcuts.py", file=sys.stderr)
            sys.exit(1)
        print(f"ok: {PAGE.name} is up to date")
        return
    PAGE.write_text(new, encoding="utf-8")
    print(f"wrote {PAGE} ({sum(len(g['keys']) for g in groups)} keys)", file=sys.stderr)


if __name__ == "__main__":
    main()
